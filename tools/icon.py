#!/usr/bin/env python3
"""Draws the app icon (64x64, 1 bit: a pencil drawing a curve, bold) and writes apps/trmnl-sketch/icon.h (the same bytes
as ~/workspace/trmnl-fw-launcher/apps/icon_c.py makes from a PBM: 1 = white) and shots/icon.png. Needs Pillow."""
import sys
from PIL import Image, ImageDraw

S = 8  # drawn 8x bigger, then thresholded
im = Image.new("L", (64 * S, 64 * S), 255)
d = ImageDraw.Draw(im)

def P(x, y):
    return (x * S, y * S)

# the curve the pencil draws: a smooth S from the lower left to the pencil's tip (a cubic Bezier)
P0, P1, P2, P3 = (5, 50), (13, 28), (19, 62), (30, 45)
pts = []
for i in range(61):
    t = i / 60
    a, b, c, e = (1 - t) ** 3, 3 * t * (1 - t) ** 2, 3 * t * t * (1 - t), t ** 3
    pts.append(P(a * P0[0] + b * P1[0] + c * P2[0] + e * P3[0], a * P0[1] + b * P1[1] + c * P2[1] + e * P3[1]))
d.line(pts, fill=0, width=5 * S, joint="curve")
for x, y in (pts[0], pts[-1]):
    d.ellipse((x - 2.5 * S, y - 2.5 * S, x + 2.5 * S, y + 2.5 * S), fill=0)
# the pencil: its tip on the end of the curve, pointing down-left; a body with outline, ferrule and eraser end
tx, ty = P3
ux, uy = 0.7071, -0.7071   # along the pencil, tip to end
vx, vy = 0.7071, 0.7071    # across
def Q(a, b):
    return P(tx + ux * a + vx * b, ty + uy * a + vy * b)
w = 7
d.polygon([Q(11, -w), Q(36, -w), Q(36, w), Q(11, w)], fill=255, outline=0, width=3 * S)
d.polygon([Q(-1, 0), Q(12, -w), Q(12, w)], fill=0)           # the sharpened tip
d.line([Q(26, -w), Q(26, w)], fill=0, width=3 * S)            # the ferrule band
d.line([Q(31, -w), Q(31, w)], fill=0, width=3 * S)
im = im.resize((64, 64), Image.BOX).point(lambda v: 0 if v < 128 else 255, "1")
im.save("shots/icon.png")
px = im.load()
out = []
for y in range(64):
    for x in range(0, 64, 8):
        out.append(sum((1 if px[x + k, y] else 0) << (7 - k) for k in range(8)))
with open("apps/trmnl-sketch/icon.h", "w") as f:
    f.write("/* Generated by tools/icon.py: the 64x64 app icon for APP_ICON (1 = white). SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0 */\n#define SKETCH_ICON \\\n")
    for i in range(0, 512, 16):
        f.write("    " + ", ".join("0x%02X" % v for v in out[i:i + 16]) + (", \\\n" if i + 16 < 512 else "\n"))
