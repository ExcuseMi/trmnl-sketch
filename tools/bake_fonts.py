"""Bakes Barlow Condensed (fonts/, SIL OFL 1.1) into 1-bit glyphs for the sizes in fonts/sizes.txt.
Usage: bake_fonts.py <out.c>. Each glyph is stored as row records: [repeat] [n] then n x (x0, len), 1 byte each, or 2 (little-endian) when
the glyph is wider than 255 px; a record stands for `repeat` equal rows.
Small sizes get all printable ASCII; big sizes the recorded characters, digits, '.:-%' and capitals up to 300 px."""
import os, sys
from PIL import Image, ImageDraw, ImageFont
HERE = os.path.dirname(os.path.abspath(__file__)); FD = os.path.join(HERE, "..", "fonts")
WEIGHTS = ["Medium", "SemiBold", "Bold"]
ASCII = "".join(chr(c) for c in range(32, 127)) + "°"
def charset(w, s, rec):
    cs = set(rec) | set("0123456789 .:-%")
    if s <= 100: cs |= set(ASCII)
    if s <= 200: cs |= set("ABCDEFGHIJKLMNOPQRSTUVWXYZ!*")
    return sorted(cs, key=ord)
def glyph(font, ch):
    adv = font.getlength(ch)
    bb = font.getbbox(ch, anchor="ls")
    if bb[2] <= bb[0] or bb[3] <= bb[1]: return adv, 0, 0, 0, 0, []
    pad = 4; W = bb[2] - bb[0] + 2 * pad; H = bb[3] - bb[1] + 2 * pad
    im = Image.new("1", (W, H), 0); d = ImageDraw.Draw(im); d.fontmode = "1"
    d.text((pad - bb[0], pad - bb[1]), ch, font=font, fill=1, anchor="ls")
    box = im.getbbox()
    if not box: return adv, 0, 0, 0, 0, []
    im = im.crop(box); w, h = im.size; px = im.load()
    rows = []
    for y in range(h):
        runs = []; x = 0
        while x < w:
            if px[x, y]:
                x0 = x
                while x < w and px[x, y]: x += 1
                runs.append((x0, x - x0))
            else: x += 1
        rows.append(runs)
    return adv, box[0] - pad + bb[0], box[1] - pad + bb[1], w, h, rows
def main(out):
    sizes = []
    for line in open(os.path.join(FD, "sizes.txt"), encoding="utf-8"):
        if line.startswith("#") or not line.strip(): continue
        w, s, *rest = line.rstrip("\n").split(" ", 2)
        sizes.append((w, int(s), rest[0] if rest else ""))
    data = bytearray(); fonts = []; glyphs = []
    for w, s, rec in sizes:
        f = ImageFont.truetype(os.path.join(FD, f"BarlowCondensed-{w}.ttf"), s)
        asc, desc = f.getmetrics(); dh = -f.getbbox("0", anchor="ls")[1]
        first = len(glyphs)
        for ch in charset(w, s, rec):
            adv, xo, yo, gw, gh, rows = glyph(f, ch)
            off = len(data)
            wide = gw > 255; i = 0
            while i < len(rows):
                r = rows[i]; rep = 1
                while i + rep < len(rows) and rows[i + rep] == r and rep < 255: rep += 1
                if len(r) > 255: raise SystemExit("too many runs")
                data += bytes((rep, len(r)))
                for x0, n in r: data += bytes((x0 & 255, x0 >> 8, n & 255, n >> 8)) if wide else bytes((x0, n))
                i += rep
            glyphs.append((ord(ch), xo, yo, gw, gh, round(adv * 64), off))
        fonts.append((WEIGHTS.index(w), s, asc, desc, dh, first, len(glyphs) - first))
    with open(out, "w") as o:
        o.write("/* Generated by tools/bake_fonts.py from Barlow Condensed (SIL Open Font License 1.1, fonts/OFL.txt).\n"
                "   Do not edit. */\n#include \"font.h\"\n\n")
        o.write(f"static const uint8_t D[{len(data)}] = {{\n")
        for i in range(0, len(data), 32): o.write(",".join(str(b) for b in data[i:i + 32]) + ",\n")
        o.write("};\n\nstatic const font_glyph_t G[] = {\n")
        for g in glyphs: o.write("{%d,%d,%d,%d,%d,%d,%d},\n" % g)
        o.write("};\n\nconst font_face_t font_faces[] = {\n")
        for (wi, s, a, d, dh, first, n) in fonts: o.write(f"{{{wi},{s},{a},{d},{dh},{n},G + {first},D}},\n")
        o.write(f"}};\nconst int font_face_count = {len(fonts)};\n")
    print(f"{out}: {len(fonts)} sizes, {len(glyphs)} glyphs, {len(data)} bytes")
main(sys.argv[1])
